/**
 * 样式编译流水线（对齐 v2 lib 产物语义）：
 * 1. 由 theme.basic/theme.components 生成 src/mixin/theme.css-vars.styl（token = var(--token)）
 *    并注入编译——组件样式统一消费 CSS 自定义属性，:root 默认值块取自主题文件当前值
 * 2. 每个组件 .styl 经 stylus 编译（注入 theme.css-vars/util 全局变量）
 * 3. postcss：autoprefixer（iOS>=8/Android>4）→ cssnano（对齐 v2 preset 微调）→ url inline
 * 4. 产物：dist/index.css（全量）+ dist/es/<name>.css（按需，头部带该组件用到的 :root 子集）
 *    + dist/global.css（可选的全局 reset 与字体）+ dist/fonts.css + dist/scoped-reset.css
 * 与 v2 差异：
 *   - index.css 不再内联 global.styl——组件库不得影响组件之外的样式，
 *     需要 v2 全局 reset 的项目自行引入 @centui/styles/global.css
 *   - px 保持原样（v2 发布产物同样不落 pxtorem，rem 转换留给用户侧 postcss）
 *   - 主题化：index.css 头部输出全量 :root 默认值，覆盖 --color-primary 等
 *     自定义属性即可重主题（引用型令牌保持 var() 链，可级联派生）
 *   - 构建末尾扫描「未解析 token 泄漏」（见 scripts/scan-leaks.mjs），发现即失败
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import stylus from 'stylus'
import postcss from 'postcss'
import autoprefixer from 'autoprefixer'
import cssnanoPlugin from 'cssnano'
import url from 'postcss-url'
import { ThemeTokens } from './theme-tokens.mjs'
import { scanLeaks } from './scan-leaks.mjs'

const ROOT = fileURLToPath(new URL('../', import.meta.url))
const SRC = join(ROOT, 'src')
const DIST = join(ROOT, 'dist')
const BROWSERS = ['iOS >= 8', 'Android > 4']

const CSS_VARS_FILE = join(SRC, 'mixin/theme.css-vars.styl')
const MIXIN_IMPORTS = [CSS_VARS_FILE, join(SRC, 'mixin/util.styl')]

/** 由主题文件重新生成 var() 化令牌表（组件编译时的全局注入源） */
function generateCssVarsStyl(theme) {
  const groups = { 'theme.components': [], 'theme.basic': [] }
  for (const t of theme.entries) groups[t.file].push(t.name)
  const lines = [
    '/**',
    '  Automatically generated by scripts/build.mjs — do not edit manually',
    '  （token = var(--token)：组件样式消费 CSS 自定义属性，:root 默认值由 build.mjs 生成）',
    '**/',
  ]
  for (const file of ['theme.components', 'theme.basic']) {
    lines.push(`/// from ${file}.styl`)
    for (const name of groups[file]) lines.push(`${name} = var(--${name})`)
  }
  lines.push('/// stylus 配置开关（非 CSS 令牌）', 'support-for-ie = false', '')
  writeFileSync(CSS_VARS_FILE, lines.join('\n'))
}

function compileStylus(source, filename) {
  return new Promise((resolve, reject) => {
    const style = stylus(source)
      .set('filename', filename)
      .set('paths', [join(SRC, 'mixin')])
    for (const imp of MIXIN_IMPORTS) {
      style.import(imp)
    }
    style.render((err, css) => (err ? reject(err) : resolve(css)))
  })
}

async function processCss(css, fromPath, toPath) {
  const result = await postcss([
    autoprefixer({ overrideBrowserslist: BROWSERS }),
    url({ url: 'inline' }),
    cssnanoPlugin({
      preset: [
        'default',
        {
          zindex: false,
          mergeIdents: false,
          discardUnused: false,
          autoprefixer: false,
          reduceIdents: false,
        },
      ],
    }),
  ]).process(css, { from: fromPath, to: toPath })
  return result.css
}

/** 产出物组装：编译 → :root 子集前缀（同样过 cssnano 保持产物风格一致）→ 泄漏扫描 */
async function buildArtifact(name, srcPath, outPath, theme) {
  const css = await processCss(await compileStylus(readFileSync(srcPath, 'utf8'), srcPath), srcPath, outPath)
  const finalCss = (await minifyRoot(theme, theme.requiredTokens(css))) + css
  const leaks = scanLeaks(finalCss).map(l => `${l.prop}: ${l.ident}`)
  if (leaks.length > 0) {
    throw new Error(`[${name}] 未解析 token 泄漏：${[...new Set(leaks)].join('、')}`)
  }
  writeFileSync(outPath, finalCss)
  return { css, tokens: theme.requiredTokens(css), leaks: 0 }
}

/** :root 默认值块经同一 postcss 管线压缩（hex 小写、去引号等，与 v2 产物风格一致） */
async function minifyRoot(theme, tokens) {
  return processCss(theme.rootBlock(tokens), join(DIST, 'root.css'), join(DIST, 'root.css'))
}

async function main() {
  const theme = new ThemeTokens(SRC)
  generateCssVarsStyl(theme)
  mkdirSync(join(DIST, 'es'), { recursive: true })

  // v2 内嵌字体（DIDIFD-Medium 数字子集）——无令牌引用，无需 :root
  const fontsPath = join(SRC, 'fonts.styl')
  const fontsCss = await processCss(
    await compileStylus(readFileSync(fontsPath, 'utf8'), fontsPath),
    fontsPath,
    join(DIST, 'fonts.css'),
  )
  writeFileSync(join(DIST, 'fonts.css'), fontsCss)

  // 组件作用域重置 + 全局基础样式（raw，供 index.css 复用，:root 由各产物自行携带）
  const raws = {}
  for (const name of ['scoped-reset', 'global']) {
    const srcPath = join(SRC, `${name}.styl`)
    raws[name] = await processCss(
      await compileStylus(readFileSync(srcPath, 'utf8'), srcPath),
      srcPath,
      join(DIST, `${name}.css`),
    )
  }
  writeFileSync(join(DIST, 'scoped-reset.css'), (await minifyRoot(theme, theme.requiredTokens(raws['scoped-reset']))) + raws['scoped-reset'])
  writeFileSync(join(DIST, 'global.css'), (await minifyRoot(theme, theme.requiredTokens(raws.global))) + raws.global)

  // 组件样式
  const files = readdirSync(join(SRC, 'components'))
    .filter(f => f.endsWith('.styl'))
    .sort()
  // index.css 为纯组件样式聚合，不含 globalCss（见文件头注释）
  const bundles = []
  const unionTokens = new Set()
  let failed = 0

  for (const file of files) {
    const name = file.replace(/\.styl$/, '')
    const srcPath = join(SRC, 'components', file)
    try {
      const { css, tokens } = await buildArtifact(name, srcPath, join(DIST, 'es', `${name}.css`), theme)
      bundles.push(css)
      for (const t of tokens) unionTokens.add(t)
    } catch (err) {
      failed++
      console.error(`FAIL ${name}: ${err.message}`)
    }
  }

  // index.css：全量 :root + 字体 + 作用域重置 + 组件聚合（对齐 v2 主产物行为）
  // union 须覆盖内嵌的 scoped-reset（fonts.styl 无令牌引用）
  for (const t of theme.requiredTokens(raws['scoped-reset'])) unionTokens.add(t)
  writeFileSync(join(DIST, 'index.css'), (await minifyRoot(theme, unionTokens)) + fontsCss + raws['scoped-reset'] + bundles.join(''))
  console.log(
    `Built ${files.length - failed}/${files.length} component styles + global.css + fonts.css + scoped-reset.css + index.css` +
      `（:root tokens: ${unionTokens.size}/${theme.map.size}, leaks: 0）`,
  )
  if (failed > 0) {
    process.exit(1)
  }
}

main()
